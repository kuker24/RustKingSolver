def list_templates():
    print(f"\n{Fore.CYAN}{'='*60}{Style.RESET_ALL}\n{Fore.WHITE}{Style.BRIGHT} Bambda Templates{Style.RESET_ALL}\n{Fore.CYAN}{'='*60}{Style.RESET_ALL}")
    for tid,t in BAMBILLA.items():
        print(f"\n  {Fore.GREEN}{tid}{Style.RESET_ALL}\n    {t['desc']}")
        for pn,pv in t["p"].items():
            dfl = pv[0] if isinstance(pv,tuple) else (pv if isinstance(pv,str) else pv[0])
            print(f"      --param {pn}={dfl}")
    print()

def infer_template(desc):
    d=desc.lower(); hints={"filter_request_by_method":["method","get","post","delete"],"filter_response_code":["status","2xx","3xx","4xx","5xx"],"highlight_by_header":["header","highlight"],"filter_by_extension":["extension","static","css","js"],"detect_auth_bypass":["auth bypass","403 bypass"],"filter_by_param":["parameter","param"],"scope_by_domain":["domain","scope"],"detect_reflected_xss":["xss","reflected","script injection"]}
    best,best_s=None,0
    for tid,kws in hints.items():
        s=sum(1 for kw in kws if kw in d)
        if s>best_s: best_s,best=s,tid
    return best,best_s

def generate(tid,params,scope="All items"):
    t=BAMBILLA[tid]; m={"scope_desc":scope}
    for pn,pv in t["p"].items():
        v=params.get(pn)
        if v is None: v=pv[0] if isinstance(pv,tuple) else (pv if isinstance(pv,str) else pv[0])
        m[pn]=v
    return "// Generated by Bambda Generator\n// "+tid+"\n// Scope: "+scope+"\n"+t["c"].format(**m)

def main():
    p=argparse.ArgumentParser(description="Bambda Script Generator")
    p.add_argument("action",nargs="?",default="list"); p.add_argument("--param","-p",action="append",default=[],dest="params"); p.add_argument("--scope",default="All items"); p.add_argument("--infer","-i"); p.add_argument("--output","-o"); p.add_argument("--dump-templates","-d",action="store_true")
    a=p.parse_args()
    if a.dump_templates: print(json.dumps(BAMBILLA,indent=2)); return
    if a.action=="list": list_templates(); return
    if a.infer:
        tid,score=infer_template(a.infer)
        if tid is None: print(f"{Fore.RED}[!] No match{Style.RESET_ALL}"); sys.exit(1)
        print(f"{Fore.GREEN}[+] Matched: {tid} (score:{score}){Style.RESET_ALL}"); a.action=tid
    if a.action not in BAMBILLA: print(f"{Fore.RED}[!] Unknown{Style.RESET_ALL}"); list_templates(); sys.exit(1)
    params={}
    for pa in a.params:
        if "=" in pa: k,v=pa.split("=",1); params[k.strip()]=v.strip()
    code=generate(a.action,params,scope=a.scope)
    print(f"\n{Fore.CYAN}{'='*60}{Style.RESET_ALL}\n{Fore.WHITE}{Style.BRIGHT} {a.action}{Style.RESET_ALL}\n{Fore.CYAN}{'='*60}{Style.RESET_ALL}\n{textwrap.dedent(code)}\n")
    if a.output:
        with open(a.output,"w") as f: f.write(code)
        print(f"{Fore.GREEN}[+] {a.output}{Style.RESET_ALL}")

if __name__ == "__main__":
    main()
